/* 将标题位图居中画入 framebuffer (黑色落到 y0 起) */
void boot_logo_draw(uint16_t y0)
{
    int x0 = (240 - BOOT_TITLE_W) / 2;
    for (int y = 0; y < BOOT_TITLE_H; y++) {
        const uint8_t *row = &boot_title_bmp[y * ((BOOT_TITLE_W + 7) / 8)];
        for (int x = 0; x < BOOT_TITLE_W; x++) {
            if (row[x / 8] & (0x80 >> (x % 8)))
                EPD_SetPixel(x0 + x, y0 + y, 0);
        }
    }
}
