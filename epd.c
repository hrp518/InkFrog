static void EPD_ForceReset(void);

/* Wait until EPD is not busy */
static void EPD_3IN52_ReadBusy(void)
{
    printf("e-Paper busy\r\n");
    uint8_t busy;
    int timeout = 0;

    // 统一3s超时
    while (timeout < 3000) {
        busy = HAL_GPIO_ReadPin(GPIO_PORT_A, GPIO_PIN_8);  // PA8 = BUSY
        if (busy == GPIO_PIN_HIGH) {
            // BUSY高=空闲，直接返回
            break;
        }
        OS_MSleep(1);
        timeout++;
    }

    if (timeout >= 3000) {
        printf("[EPD] ReadBusy timeout (EPD可能还在刷新或处于异常状态)\r\n");
    } else {
        OS_MSleep(50);
        printf("e-Paper busy release\r\n");
    }
}

/* Refresh display */
static void EPD_3IN52_refresh(void)
{
    EPD_SendCommand(0x17);
    EPD_SendData(0xA5);
    EPD_3IN52_ReadBusy();
    OS_MSleep(200);
}

/* LUT download for GC mode */
static void EPD_3IN52_lut_GC(void)
{
    uint8_t count;
    
    EPD_SendCommand(0x20);  // vcom
    for (count = 0; count < 56; count++) {
        EPD_SendData(EPD_3IN52_lut_R20_GC[count]);
    }
    
    EPD_SendCommand(0x21);  // red not use
    for (count = 0; count < 42; count++) {
        EPD_SendData(EPD_3IN52_lut_R21_GC[count]);
    }
    
    EPD_SendCommand(0x24);  // bb b
    for (count = 0; count < 42; count++) {
        EPD_SendData(EPD_3IN52_lut_R24_GC[count]);
    }
    
    if (EPD_3IN52_Flag == 0) {
        EPD_SendCommand(0x22);  // bw r
        for (count = 0; count < 56; count++) {
            EPD_SendData(EPD_3IN52_lut_R22_GC[count]);
        }
        
        EPD_SendCommand(0x23);  // wb w
        for (count = 0; count < 42; count++) {
            EPD_SendData(EPD_3IN52_lut_R23_GC[count]);
        }
        
        EPD_3IN52_Flag = 1;
    } else {
        EPD_SendCommand(0x22);  // bw r
        for (count = 0; count < 56; count++) {
            EPD_SendData(EPD_3IN52_lut_R23_GC[count]);
        }
        
        EPD_SendCommand(0x23);  // wb w
        for (count = 0; count < 42; count++) {
            EPD_SendData(EPD_3IN52_lut_R22_GC[count]);
        }
        
        EPD_3IN52_Flag = 0;
    }
}

/* Clear screen */
void EPD_3IN52_Clear(void)
{
    // Wait for EPD idle before starting new operation
    int timeout = 0;
    while (timeout < 3000) {
        if (HAL_GPIO_ReadPin(GPIO_PORT_A, GPIO_PIN_8) == GPIO_PIN_HIGH) break;
        OS_MSleep(1);
        timeout++;
    }
    if (timeout >= 3000) {
        printf("[EPD] Clear: BUSY stuck LOW before clear, forcing reinit...\n");
        // Force EPD out of unknown state, then retry
        EPD_ForceReset();
        timeout = 0;
        while (timeout < 3000) {
            if (HAL_GPIO_ReadPin(GPIO_PORT_A, GPIO_PIN_8) == GPIO_PIN_HIGH) break;
            OS_MSleep(1);
            timeout++;
        }
        if (timeout >= 3000) {
            printf("[EPD] Clear: still stuck, proceeding anyway\n");
        }
    }

    EPD_SendCommand(0x13);

    // 240 x 415 = 12450 bytes
    for (int i = 0; i < 12450; i++) {
        EPD_SendData(0xFF);
    }

    EPD_3IN52_lut_GC();
    EPD_3IN52_refresh();

    EPD_SendCommand(0x50);
    EPD_SendData(0x17);

    // Wait for BUSY HIGH to confirm full GC refresh completed
    timeout = 0;
    while (timeout < 3000) {
        if (HAL_GPIO_ReadPin(GPIO_PORT_A, GPIO_PIN_8) == GPIO_PIN_HIGH) break;
        OS_MSleep(1);
        timeout++;
    }
    if (timeout >= 3000) {
        printf("[EPD] Clear: BUSY stuck LOW after refresh (EPD may be in inconsistent state)\n");
    }
}

/* Check if EPD is responding */
static int EPD_CheckReady(void)
{
    uint8_t busy;
    int timeout = 0;
    
    while (timeout < 3000) {
        busy = HAL_GPIO_ReadPin(GPIO_PORT_A, GPIO_PIN_8);  // PA8 = BUSY
        if (busy == GPIO_PIN_HIGH) {
            return 0;  // Ready
        }
        OS_MSleep(1);
        timeout++;
    }
    
    printf("[EPD] Device not ready (BUSY timeout)\n");
    return -1;  // Not ready
}

/*
 * Forced hardware reset + full initialization
 * Call this when EPD is in unknown/inconsistent state (e.g., after deep-sleep, unexpected power loss)
 */
static void EPD_ForceReset(void)
{
    HAL_GPIO_WritePin(GPIO_PORT_A, GPIO_PIN_9, GPIO_PIN_HIGH);  // RST HIGH
    OS_MSleep(200);
    HAL_GPIO_WritePin(GPIO_PORT_A, GPIO_PIN_9, GPIO_PIN_LOW);   // RST LOW
    OS_MSleep(2);
    HAL_GPIO_WritePin(GPIO_PORT_A, GPIO_PIN_9, GPIO_PIN_HIGH);  // RST HIGH
    OS_MSleep(200);
    // Wait for EPD to stabilize (BUSY HIGH = ready)
    int timeout = 0;
    while (timeout < 3000) {
        if (HAL_GPIO_ReadPin(GPIO_PORT_A, GPIO_PIN_8) == GPIO_PIN_HIGH) break;
        OS_MSleep(1);
        timeout++;
    }
    if (timeout >= 3000) {
        printf("[EPD] ForceReset: BUSY still low after 3s (EPD may still be waking up)\n");
    }
}

