/* GC 全刷发整帧(同步)：调 EPD_3IN52_Display，它在 GC 前会重发面板参数。 */
int EPD_3IN52_Display_GC_Sync(const uint8_t *frame)
{
    if (frame && frame != framebuffer) {
        /* 时钟路径通常用全局 framebuffer，这里兼容外部缓冲区 */
        memcpy(framebuffer, frame, 240 * 415 / 8);
    }
    EPD_3IN52_Display();
    if (EPD_WaitIdle(5000) != 0) {
        return -1;
    }
    return 0;
}

