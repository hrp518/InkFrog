/* 等待 BUSY(PA8) 高电平(空闲)。timeout_ms 超时返回非0。 */
int EPD_WaitIdle(uint32_t timeout_ms)
{
    uint32_t waited = 0;
    while (waited < timeout_ms) {
        if (HAL_GPIO_ReadPin(GPIO_PORT_A, GPIO_PIN_8) == GPIO_PIN_HIGH) {
            return 0;
        }
        OS_MSleep(1);
        waited++;
    }
    printf("[EPD] WaitIdle timeout (%ums)\r\n", (unsigned)timeout_ms);
    return -1;
}

/* DU 模式初始化(同步)：调现有 Init_DU 流程，失败返回非0。
 * Init_DU 内部已含 reset + BUSY 等待 + 面板参数 + 自愈重试，
 * 这里仅在末尾再校验一次 BUSY 空闲作为返回值。 */
int EPD_3IN52_Init_DU_Sync(void)
{
    EPD_3IN52_Init_DU();
    if (EPD_WaitIdle(3000) != 0) {
        return -1;
    }
    return 0;
}

/* DU 发整帧 + 刷新(同步)。
 * 复用 Display_DU 的"等 BUSY→重发面板参数→发 framebuffer→LUT→refresh"流程，
 * 但用传入的 frame 指针(通常就是全局 framebuffer)以显式表达所有权。 */
int EPD_3IN52_Display_DU_Sync(const uint8_t *frame)
{
    int timeout;

    if (!frame) {
        frame = framebuffer;
    }

    /* 1. 等 BUSY 空闲；卡死则走 Init+Init_DU 自愈(同 Display_DU) */
    timeout = 0;
    while (timeout < 3000) {
        if (HAL_GPIO_ReadPin(GPIO_PORT_A, GPIO_PIN_8) == GPIO_PIN_HIGH) break;
        OS_MSleep(1);
        timeout++;
    }
    if (timeout >= 3000) {
        printf("[EPD] DU_Sync: BUSY stuck, forcing reinit\r\n");
        if (EPD_3IN52_Init() != 0) {
            return -1;
        }
        EPD_3IN52_Init_DU();
        OS_MSleep(500);
        if (EPD_WaitIdle(3000) != 0) {
            return -1;
        }
    }

    /* 2. 重发面板参数(DU) */
    EPD_SendCommand(0x00); EPD_SendData(0xFF); EPD_SendData(0x01);
    EPD_SendCommand(0x01); EPD_SendData(0x03); EPD_SendData(0x10);
    EPD_SendData(0x3F);   EPD_SendData(0x3F); EPD_SendData(0x03);
    EPD_SendCommand(0x06); EPD_SendData(0x37); EPD_SendData(0x3D); EPD_SendData(0x3D);
    EPD_SendCommand(0x60); EPD_SendData(0x22);
    EPD_SendCommand(0x82); EPD_SendData(0x07);
    EPD_SendCommand(0x30); EPD_SendData(0x09);
    EPD_SendCommand(0xe3); EPD_SendData(0x88);
    EPD_SendCommand(0x50); EPD_SendData(0xB7);

    /* 3. 发整帧 framebuffer */
    EPD_SendCommand(0x13);
    for (int i = 0; i < 240 * 415 / 8; i++) {
        EPD_SendData(frame[i]);
    }

    /* 4. DU LUT + 刷新触发(0x17/0xA5) + 等 BUSY + 保护延时 */
    EPD_3IN52_lut_DU();
    EPD_3IN52_refresh();   /* 内部已含 ReadBusy(3s)+200ms 保护 */
    OS_MSleep(2);

    if (EPD_WaitIdle(3000) != 0) {
        return -1;
    }
    return 0;
}

